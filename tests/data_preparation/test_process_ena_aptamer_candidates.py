def _base_record(**kwargs):
    rec = {
        "accession": "TEST0001",
        "sequence_version": "1",
        "description": "",
        "organism": "synthetic construct",
        "molecule_type": "unassigned RNA",
        "reported_length": "40",
        "record_length": 40,
        "sequence_deposited": "GGGACGAAGCTTAAAACGACGGCCAGTGCCAAGCTTGCAT",
        "sequence_alphabet": "DNA_alphabet",
        "feature_notes": "",
        "products": "",
        "keywords": "",
        "reference_titles": "",
        "doi_values": "",
        "pubmed_values": "",
        "mentions_selex": False,
        "mentions_in_vitro_selection": False,
        "mentions_synthetic_construct": True,
        "contains_t7_promoter_like_motif": False,
        "signal_natural_or_genomic": False,
        "signal_riboswitch_related": False,
        "signal_engineered_construct": False,
        "signal_dna_template_or_promoter": False,
        "signal_reverse_complement_feature": False,
        "has_complement_feature": False,
        "matched_selection_terms": "",
        "parse_warnings": "",
    }
    rec.update(kwargs)
    if "record_length" not in kwargs and "reported_length" in kwargs:
        rec["record_length"] = int(kwargs["reported_length"])
    return rec


def _tier_for(rec, feature_info=None):
    rna = assess_rna_identity(rec)
    target = assess_target(rec)
    binding = assess_binding(rec, target.fields)
    selection = assess_selection(rec)
    role = assess_sequence_role(rec, rna.fields, feature_info)
    tier = assign_candidate_tier(
        rec, rna.fields, target.fields, binding.fields, selection.fields, role.fields
    )
    return {
        "rna": rna.fields,
        "target": target.fields,
        "binding": binding.fields,
        "selection": selection.fields,
        "role": role.fields,
        "tier": tier.fields,
    }


